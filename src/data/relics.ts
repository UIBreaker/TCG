export const getRelicById = (id: string): Relic | undefined => {
  return ALL_RELICS.find(r => r.id === id);
};

export const getRandomRelic = (excludeIds: string[] = []): Relic => {
  const available = ALL_RELICS.filter(r => !excludeIds.includes(r.id));
  if (available.length === 0) return ALL_RELICS[0];
  return available[Math.floor(Math.random() * available.length)];
};
